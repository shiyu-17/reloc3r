#!/usr/bin/env python3
"""Run the pre-registered, non-Agent AVL-003 ablations.

All selectors operate only on the mapping poses, retrieved indices and the
Reloc3r relative-pose candidates already written by AVL-002.  Query GT is
kept out of every selector (it is read by the evaluation branch only); the
oracle methods are explicit upper bounds and are never presented as deployable
methods.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from itertools import combinations

import numpy as np
from scipy.spatial.transform import Rotation

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from tools.eval_lilocbench_reloc3r import (  # noqa: E402
    average_from_relative,
    base_to_front_rgb_optical,
    pose_error,
    read_manifest,
    tum_camera_poses,
    failure_runs,
)


SEQUENCES = ("static_0", "dynamics_0", "lt_changes_0", "lt_changes_dynamics_0")
SUCCESS_T = 0.25
SUCCESS_R = 5.0


def rotation_distance(first, second):
    return float(np.degrees(Rotation.from_matrix(first[:3, :3].T @ second[:3, :3]).magnitude()))


def load_relative(result_root: Path, frame_count: int):
    out = [None] * frame_count
    for path in sorted(result_root.glob("relative_poses_shard_*_of_*.npz")):
        data = np.load(path)
        for idx, query_index in enumerate(data["query_indices"]):
            out[int(query_index)] = {
                "indices": data["mapping_indices"][idx].astype(np.int64),
                "relative": data["relative_poses"][idx].astype(np.float64),
            }
    if any(item is None for item in out):
        missing = [i for i, item in enumerate(out) if item is None]
        raise RuntimeError(f"Missing relative pose shards for query indices {missing[:10]}")
    return out


def candidate_distances(candidates):
    """Return a geometry-only distance matrix for candidate absolute poses."""
    n = len(candidates)
    result = np.zeros((n, n), dtype=np.float64)
    for i, j in combinations(range(n), 2):
        dt = np.linalg.norm(candidates[i][:3, 3] - candidates[j][:3, 3])
        dr = rotation_distance(candidates[i], candidates[j])
        # A 1 m / 10 degree normalization avoids either term dominating by
        # units while keeping the thresholds interpretable in the registry.
        result[i, j] = result[j, i] = dt / 1.0 + dr / 10.0
    return result


def select_consensus(candidates, k):
    if len(candidates) <= k:
        return list(range(len(candidates)))
    distances = candidate_distances(candidates)
    medoid = int(np.argmin(distances.sum(axis=1)))
    order = np.argsort(distances[medoid], kind="stable")
    return [int(i) for i in order[:k]]


def select_verify(candidates, k=10, translation_radius=1.0, rotation_radius=20.0):
    """Geometry-only candidate verification with a deterministic fallback."""
    distances = candidate_distances(candidates)
    medoid = int(np.argmin(distances.sum(axis=1)))
    accepted = []
    for idx, candidate in enumerate(candidates):
        dt = np.linalg.norm(candidate[:3, 3] - candidates[medoid][:3, 3])
        dr = rotation_distance(candidate, candidates[medoid])
        if dt <= translation_radius and dr <= rotation_radius:
            accepted.append(idx)
    if not accepted:
        accepted = [medoid]
    accepted.sort(key=lambda idx: (distances[medoid, idx], idx))
    return accepted[:k], medoid


def aggregate_selected(mapping_poses, relative_poses, indices):
    indices = list(indices)
    prediction, _ = average_from_relative(
        [mapping_poses[i] for i in indices], [relative_poses[i] for i in indices])
    return prediction


def evaluate_prediction(prediction, ground_truth):
    t, r = pose_error(prediction, ground_truth)
    return {
        "translation_error_m": float(t),
        "rotation_error_deg": float(r),
        "success_0.25m_5deg": bool(t <= SUCCESS_T and r <= SUCCESS_R),
    }


def select_methods(candidates, mapping_indices, relative_poses, previous_memory):
    """Return selections and metadata. No GT is available in this function."""
    count = len(candidates)
    methods = {}
    for k in (1, 3, 5, 10):
        methods[f"top{k}"] = {"indices": list(range(min(k, count))), "fallback": False}
    for k in (3, 5, 10):
        methods[f"consensus{k}"] = {"indices": select_consensus(candidates, k), "fallback": False}
    verified, medoid = select_verify(candidates, 10, 1.0, 20.0)
    methods["verify10_t1.0_r20"] = {"indices": verified, "fallback": len(verified) < 2,
                                    "medoid": medoid}

    # A memory prior is only the previous accepted prediction generated by
    # this same method. It never reads query GT or future frames.
    if previous_memory is None:
        memory_indices = select_consensus(candidates, 3)
        memory_fallback = True
    else:
        distances = []
        for idx, candidate in enumerate(candidates):
            dt = np.linalg.norm(candidate[:3, 3] - previous_memory[:3, 3])
            dr = rotation_distance(candidate, previous_memory)
            distances.append((dt + dr / 10.0, dt, dr, idx))
        local = [item for item in sorted(distances) if item[1] <= 1.5 and item[2] <= 30.0]
        if local:
            memory_indices = [item[3] for item in local[:3]]
            memory_fallback = False
        else:
            memory_indices = select_consensus(candidates, 3)
            memory_fallback = True
    methods["memory3"] = {"indices": memory_indices, "fallback": memory_fallback}
    return methods


def analyse_sequence(args, sequence):
    result_root = args.results_root / sequence
    _, db_frames, db_times, _, db_root = read_manifest(args.data_root, "mapping")
    _, query_frames, query_times, _, query_root = read_manifest(args.data_root, sequence)
    db_pose, _ = tum_camera_poses(args.mapping_gt, db_times,
                                  base_to_front_rgb_optical(db_root), args.max_gt_delta)
    query_pose, query_delta = tum_camera_poses(args.gt_dir / f"{sequence}_gt_poses.txt", query_times,
                                              base_to_front_rgb_optical(query_root), args.max_gt_delta)
    relative = load_relative(result_root, len(query_frames))
    method_rows = {}
    previous_memory = None
    oracle_rows = []
    for query_index, item in enumerate(relative):
        mapping_indices = item["indices"]
        rel_poses = item["relative"]
        candidates = [db_pose[int(idx)] @ rel for idx, rel in zip(mapping_indices, rel_poses)]
        selections = select_methods(candidates, mapping_indices, rel_poses, previous_memory)
        frame_output = {
            "query_index": query_index,
            "timestamp": float(query_times[query_index]),
            "gt_delta_s": float(query_delta[query_index]),
            "reference_indices": mapping_indices.tolist(),
            "methods": {},
        }
        for name, selection in selections.items():
            prediction = aggregate_selected(db_pose[mapping_indices], rel_poses, selection["indices"])
            metrics = evaluate_prediction(prediction, query_pose[query_index])
            selected_candidates = [candidates[i] for i in selection["indices"]]
            selected_disp_t = 0.0
            selected_disp_r = 0.0
            if len(selected_candidates) > 1:
                pairs = list(combinations(selected_candidates, 2))
                selected_disp_t = float(np.median([np.linalg.norm(a[:3, 3] - b[:3, 3]) for a, b in pairs]))
                selected_disp_r = float(np.median([rotation_distance(a, b) for a, b in pairs]))
            frame_output["methods"][name] = {
                **metrics,
                "selected_candidate_positions": selection["indices"],
                "fallback": bool(selection.get("fallback", False)),
                "internal_candidate_dispersion_m": selected_disp_t,
                "internal_candidate_dispersion_deg": selected_disp_r,
            }
            method_rows.setdefault(name, []).append({**metrics, "fallback": bool(selection.get("fallback", False))})
            if name == "memory3":
                # Retain only an internally consistent prior. This gate uses
                # candidate geometry, never query GT, so stale/bad history is
                # not allowed to become a self-reinforcing memory state.
                internally_reliable = (
                    len(selected_candidates) >= 2
                    and selected_disp_t <= 1.5
                    and selected_disp_r <= 15.0
                )
                frame_output["methods"][name]["internal_reliable"] = internally_reliable
                if internally_reliable:
                    previous_memory = prediction

        # Oracle candidate and oracle prefix are evaluation-only upper bounds.
        candidate_metrics = [evaluate_prediction(candidate, query_pose[query_index]) for candidate in candidates]
        oracle_idx = int(np.argmin([m["translation_error_m"] / SUCCESS_T +
                                    m["rotation_error_deg"] / SUCCESS_R for m in candidate_metrics]))
        oracle_candidate = {**candidate_metrics[oracle_idx], "selected_candidate_positions": [oracle_idx],
                            "selection_uses_gt": True, "upper_bound_only": True}
        prefixes = []
        for k in (1, 3, 5, 10):
            idxs = list(range(min(k, len(candidates))))
            pred = aggregate_selected(db_pose[mapping_indices], rel_poses, idxs)
            metric = evaluate_prediction(pred, query_pose[query_index])
            prefixes.append((metric["translation_error_m"] / SUCCESS_T +
                             metric["rotation_error_deg"] / SUCCESS_R, metric, idxs))
        _, oracle_prefix, oracle_prefix_indices = min(prefixes, key=lambda x: x[0])
        frame_output["oracle_candidate"] = oracle_candidate
        frame_output["oracle_best_prefix"] = {**oracle_prefix,
                                                "selected_candidate_positions": oracle_prefix_indices,
                                                "selection_uses_gt": True,
                                                "upper_bound_only": True}
        oracle_rows.append(frame_output)
        frame_output["selection_uses_gt"] = False

    # Add aggregate metrics for deployable methods and separate oracle metrics.
    summary = {"sequence": sequence, "frames": len(query_frames), "gt_is_evaluation_only": True,
               "methods": {}}
    for name, rows in method_rows.items():
        runs = failure_runs([r["success_0.25m_5deg"] for r in rows], query_times)
        summary["methods"][name] = {
            "median_translation_error_m": float(np.median([r["translation_error_m"] for r in rows])),
            "median_rotation_error_deg": float(np.median([r["rotation_error_deg"] for r in rows])),
            "success_rate_0.25m_5deg": float(np.mean([r["success_0.25m_5deg"] for r in rows])),
            "fallback_rate": float(np.mean([r.get("fallback", False) for r in rows])),
            "failure_runs": len(runs),
            "median_failure_frames": float(np.median([r["frames"] for r in runs])) if runs else 0.0,
            "max_failure_frames": int(max((r["frames"] for r in runs), default=0)),
            "selection_uses_gt": False,
        }
    for name in ("oracle_candidate", "oracle_best_prefix"):
        rows = [frame[name] for frame in oracle_rows]
        summary["methods"][name] = {
            "median_translation_error_m": float(np.median([r["translation_error_m"] for r in rows])),
            "median_rotation_error_deg": float(np.median([r["rotation_error_deg"] for r in rows])),
            "success_rate_0.25m_5deg": float(np.mean([r["success_0.25m_5deg"] for r in rows])),
            "failure_runs": len(failure_runs([r["success_0.25m_5deg"] for r in rows], query_times)),
            "max_failure_frames": int(max((r["frames"] for r in failure_runs([r["success_0.25m_5deg"] for r in rows], query_times)), default=0)),
            "selection_uses_gt": True,
            "upper_bound_only": True,
        }
    out_dir = args.output_dir / sequence
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "frame_results.jsonl").write_text(
        "".join(json.dumps(row) + "\n" for row in oracle_rows), encoding="utf-8")
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    return summary


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-root", type=Path, required=True)
    parser.add_argument("--results-root", type=Path, required=True)
    parser.add_argument("--mapping-gt", type=Path, required=True)
    parser.add_argument("--gt-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--max-gt-delta", type=float, default=0.1)
    parser.add_argument("--sequences", nargs="+", default=list(SEQUENCES))
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    summaries = [analyse_sequence(args, sequence) for sequence in args.sequences]
    (args.output_dir / "summary_all.json").write_text(json.dumps(summaries, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(summaries, indent=2))


if __name__ == "__main__":
    main()
