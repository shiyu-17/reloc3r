#!/usr/bin/env python3
"""Independent GT evaluator for AVL-009 causal sequence traces.

The online traces are generated by ``run_avl009_sequence_baseline.py`` without
query GT.  This script is the only AVL-009 component that reads query poses.
It computes validation/test metrics, sequence failure analysis and a cost
ledger.  It never modifies the frozen threshold configuration.
"""

from __future__ import annotations

