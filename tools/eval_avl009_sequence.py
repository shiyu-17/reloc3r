import json
import math
import sys
from pathlib import Path

import numpy as np
from scipy.spatial.transform import Rotation

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
if str(REPOSITORY_ROOT) not in sys.path:
    sys.path.insert(0, str(REPOSITORY_ROOT))

from tools.eval_lilocbench_reloc3r import base_to_front_rgb_optical, pose_error, read_manifest, tum_camera_poses  # noqa: E402


SEQUENCES = ("static_0", "dynamics_0", "lt_changes_0", "lt_changes_dynamics_0")
METHODS = ("top10", "consensus3", "memory3", "temporal_only", "global_temporal",
           "global_temporal_memory", "global_temporal_memory_roma_recovery", "always_roma")
GT_THRESH_T = 0.25
GT_THRESH_R = 5.0


def finite_pose(pose):
    if pose is None:
        return False
    pose = np.asarray(pose, dtype=np.float64)
    return pose.shape == (4, 4) and np.isfinite(pose).all() and np.linalg.norm(
        pose[3] - np.array([0.0, 0.0, 0.0, 1.0])
    ) < 1e-3


def distance(first, second):
    first, second = np.asarray(first), np.asarray(second)
    dt = float(np.linalg.norm(first[:3, 3] - second[:3, 3]))
    dr = float(np.degrees(Rotation.from_matrix(first[:3, :3].T @ second[:3, :3]).magnitude()))
    return dt, dr


def runs(success, timestamps, offset=0):
    output = []
    begin = None
    for local, value in enumerate(success):
        if not value and begin is None:
            begin = local
        if (value or local == len(success) - 1) and begin is not None:
            end = local - 1 if value else local
            output.append({"start_index": int(offset + begin), "end_index": int(offset + end),
                           "frames": int(end - begin + 1),
                           "seconds": float(timestamps[offset + end] - timestamps[offset + begin])})
            begin = None
    return output


def recovery_latencies(success, offset=0):
    values = []
    start = None
    for local, ok in enumerate(success):
        if not ok and start is None:
            start = local
        if ok and start is not None:
            values.append(int(local - start))
            start = None
    return values


def metrics_from_predictions(predictions, ground_truth, timestamps, start=0, end=None, actions=None, sources=None):
    end = len(predictions) if end is None else end
    full_timestamps = timestamps
    predictions = predictions[start:end]
    ground_truth = ground_truth[start:end]
    timestamps = timestamps[start:end]
    n = len(predictions)
    available = np.asarray([finite_pose(p) for p in predictions], dtype=bool)
    t_errors = np.full(n, np.inf, dtype=np.float64)
    r_errors = np.full(n, np.inf, dtype=np.float64)
    for i, (prediction, gt) in enumerate(zip(predictions, ground_truth)):
        if available[i]:
            t_errors[i], r_errors[i] = pose_error(np.asarray(prediction), gt)
    success = (t_errors <= GT_THRESH_T) & (r_errors <= GT_THRESH_R)
    failure_runs = runs(success, full_timestamps, offset=start)
    run_lengths = [r["frames"] for r in failure_runs]
    latencies = recovery_latencies(success, offset=start)

    jump_values = []
    for i in range(1, n):
        if available[i - 1] and available[i]:
            predicted_motion = np.linalg.inv(predictions[i - 1]) @ predictions[i]
            gt_motion = np.linalg.inv(ground_truth[i - 1]) @ ground_truth[i]
            jump_values.append(distance(predicted_motion, gt_motion))
    jump_values = np.asarray(jump_values, dtype=np.float64).reshape((-1, 2)) if jump_values else np.empty((0, 2))
    if actions is None:
        actions = [None] * n
    else:
        actions = actions[start:end]
    if sources is None:
        sources = [None] * n
    else:
        sources = sources[start:end]
    action_counts = {}
    for action in actions:
        action_counts[str(action)] = action_counts.get(str(action), 0) + 1
    source_temporal_fail = []
    source_temporal_run = []
    current_fail = 0
    current_run = 0
    for source, ok in zip(sources, success):
        if source == "temporal":
            current_run += 1
            current_fail = current_fail + 1 if not ok else 0
        else:
            if current_run:
                source_temporal_run.append(current_run)
            if current_fail:
                source_temporal_fail.append(current_fail)
            current_run = current_fail = 0
    if current_run:
        source_temporal_run.append(current_run)
    if current_fail:
        source_temporal_fail.append(current_fail)
    return {
        "frames": int(n),
        "pose_available": int(available.sum()),
        "coverage": float(available.mean()) if n else 0.0,
        "success_count": int(success.sum()),
        "success_rate_all_frames": float(success.mean()) if n else 0.0,
        "success_rate_on_covered": float(success[available].mean()) if available.any() else 0.0,
        "median_translation_error_m": float(np.median(t_errors[available])) if available.any() else None,
        "median_rotation_error_deg": float(np.median(r_errors[available])) if available.any() else None,
        "max_failure_frames": int(max(run_lengths, default=0)),
        "mean_failure_frames": float(np.mean(run_lengths)) if run_lengths else 0.0,
        "median_failure_frames": float(np.median(run_lengths)) if run_lengths else 0.0,
        "failure_run_count": len(failure_runs),
        "failure_runs": failure_runs,
        "recovery_latency_frames": {
            "count": len(latencies), "mean": float(np.mean(latencies)) if latencies else None,
            "median": float(np.median(latencies)) if latencies else None,
            "max": int(max(latencies, default=0)),
        },
        "trajectory_jump": {
            "valid_transitions": int(len(jump_values)),
            "median_translation_m": float(np.median(jump_values[:, 0])) if len(jump_values) else None,
            "median_rotation_deg": float(np.median(jump_values[:, 1])) if len(jump_values) else None,
            "rate_gt_1m_or_20deg": float(np.mean((jump_values[:, 0] > 1.0) | (jump_values[:, 1] > 20.0))) if len(jump_values) else None,
        },
        "reject_rate": float(action_counts.get("reject", 0) / n) if n else 0.0,
        "global_call_rate": float(action_counts.get("accept_global", 0) / n) if n else 0.0,
        "temporal_call_rate": float(action_counts.get("accept_temporal", 0) / n) if n else 0.0,
        "roma_call_rate": float(action_counts.get("call_roma", 0) / n) if n else 0.0,
        "action_counts": action_counts,
        "temporal_source_failure_max": int(max(source_temporal_fail, default=0)),
        "temporal_source_run_max": int(max(source_temporal_run, default=0)),
        "success_vector": success.tolist(),
    }


def load_trace(root: Path, sequence: str):
    rows = {}
    for family in ("sequence_baseline", "sequence_memory", "sequence_recovery"):
        path = root / family / sequence / "trace.jsonl"
        for line in path.read_text(encoding="utf-8").splitlines():
            row = json.loads(line)
            rows.setdefault(int(row["query_index"]), {}).update(row["methods"])
    ordered = [rows[i] for i in sorted(rows)]
    if not ordered:
        raise RuntimeError(f"No AVL-009 trace for {sequence}")
    return ordered


def load_always_roma(path: Path, timed_path: Path | None = None):
    data = json.loads(path.read_text(encoding="utf-8"))
    rows = sorted(data["frames"], key=lambda x: x["query_index"])
    timed = {}
    if timed_path is not None and timed_path.exists():
        for line in timed_path.read_text(encoding="utf-8").splitlines():
            if line.strip():
                row = json.loads(line)
                timed[int(row["query_index"])] = row
    predictions = [None] * len(rows)
    errors = []
    success = []
    actions = []
    sources = []
    for row in rows:
        metric = row.get("metric")
        timed_row = timed.get(int(row["query_index"]))
        pose = np.asarray(timed_row["pose"], dtype=np.float64) if timed_row and timed_row.get("pose") is not None else None
        if metric is None or not row.get("pose_available", False):
            errors.append((math.inf, math.inf)); success.append(False); predictions[row["query_index"]] = None
        else:
            errors.append((float(metric["translation_error_m"]), float(metric["rotation_error_deg"])))
            success.append(bool(metric["success_0.25m_5deg"])); predictions[row["query_index"]] = pose if finite_pose(pose) else None
        actions.append("call_roma")
        sources.append("roma")
    return {"rows": rows, "errors": errors, "success": success, "predictions": predictions, "actions": actions, "sources": sources}


def metrics_from_always_roma(data, timestamps, start=0, end=None):
    end = len(data["errors"]) if end is None else end
    full_timestamps = timestamps
    errors = data["errors"][start:end]
    success = np.asarray(data["success"][start:end], dtype=bool)
    ts = timestamps[start:end]
    failure_runs = runs(success, full_timestamps, offset=start)
    lengths = [r["frames"] for r in failure_runs]
    latencies = recovery_latencies(success, offset=start)
    return {
        "frames": len(errors), "pose_available": int(sum(np.isfinite(t) for t, _ in errors)),
        "coverage": float(sum(np.isfinite(t) for t, _ in errors) / len(errors)) if errors else 0.0,
        "success_count": int(success.sum()), "success_rate_all_frames": float(success.mean()) if len(success) else 0.0,
        "success_rate_on_covered": float(success[np.asarray([np.isfinite(t) for t, _ in errors])].mean()) if any(np.isfinite(t) for t, _ in errors) else 0.0,
        "median_translation_error_m": float(np.median([t for t, _ in errors if np.isfinite(t)])) if any(np.isfinite(t) for t, _ in errors) else None,
        "median_rotation_error_deg": float(np.median([r for _, r in errors if np.isfinite(r)])) if any(np.isfinite(r) for _, r in errors) else None,
        "max_failure_frames": int(max(lengths, default=0)), "mean_failure_frames": float(np.mean(lengths)) if lengths else 0.0,
        "median_failure_frames": float(np.median(lengths)) if lengths else 0.0, "failure_run_count": len(failure_runs),
        "failure_runs": failure_runs,
        "recovery_latency_frames": {"count": len(latencies), "mean": float(np.mean(latencies)) if latencies else None,
                                     "median": float(np.median(latencies)) if latencies else None, "max": int(max(latencies, default=0))},
        "trajectory_jump": {"valid_transitions": None, "median_translation_m": None, "median_rotation_deg": None,
                             "rate_gt_1m_or_20deg": None},
        "reject_rate": 0.0, "global_call_rate": 0.0, "temporal_call_rate": 0.0, "roma_call_rate": 1.0,
        "action_counts": {"always_roma": len(errors)}, "temporal_source_failure_max": 0, "temporal_source_run_max": 0,
        "success_vector": success.tolist(), "note": "Loaded from the independent AVL-005 RoMa evaluator; pose matrices were not retained there.",
    }


def method_predictions(trace_rows, method):
    rows = [r[method] for r in trace_rows]
    return [np.asarray(r["pose"], dtype=np.float64) if r.get("pose") is not None else None for r in rows], rows


def aggregate_metrics(per_sequence):
    output = {}
    for method in METHODS:
        entries = [v[method] for v in per_sequence.values() if method in v]
        if not entries:
            continue
        frames = sum(e["frames"] for e in entries)
        output[method] = {
            "frames": frames,
            "pose_available": sum(e["pose_available"] for e in entries),
            "coverage": sum(e["pose_available"] for e in entries) / frames,
            "success_count": sum(e["success_count"] for e in entries),
            "success_rate_all_frames": sum(e["success_count"] for e in entries) / frames,
            "max_failure_frames": max(e["max_failure_frames"] for e in entries),
            "mean_failure_frames_unweighted": float(np.mean([e["mean_failure_frames"] for e in entries])),
            "median_failure_frames_unweighted": float(np.median([e["median_failure_frames"] for e in entries])),
            "failure_run_count": sum(e["failure_run_count"] for e in entries),
            "recovery_latency_mean_unweighted": float(np.mean([e["recovery_latency_frames"]["mean"] for e in entries if e["recovery_latency_frames"]["mean"] is not None])) if any(e["recovery_latency_frames"]["mean"] is not None for e in entries) else None,
            "reject_rate_frame_weighted": sum(e["reject_rate"] * e["frames"] for e in entries) / frames,
            "global_call_rate_frame_weighted": sum(e["global_call_rate"] * e["frames"] for e in entries) / frames,
            "temporal_call_rate_frame_weighted": sum(e["temporal_call_rate"] * e["frames"] for e in entries) / frames,
            "roma_call_rate_frame_weighted": sum(e["roma_call_rate"] * e["frames"] for e in entries) / frames,
        }
    return output


def cost_ledger(args, traces_by_sequence, sequence_summaries):
    timing_path = args.cost_root / "reloc3r_timing.json"
    timing = json.loads(timing_path.read_text(encoding="utf-8")) if timing_path.exists() else None
    retrieval_path = args.cost_root.parent / "retrieval_profile.json"
    retrieval = json.loads(retrieval_path.read_text(encoding="utf-8")) if retrieval_path.exists() else None
    temporal_total = 0.0
    temporal_rows = {}
    for sequence in SEQUENCES:
        total = 0.0
        for manifest in sorted((args.temporal_root / sequence).glob("edges_shard_*.json")):
            data = json.loads(manifest.read_text(encoding="utf-8"))
            total += float(data.get("elapsed_s", 0.0))
        temporal_rows[sequence] = {"sum_s": total, "measurement": "sum of measured edge inference batch wall times; preprocessing not separately instrumented"}
        temporal_total += total
    global_rows = {}
    global_total = 0.0
    retrieval_total = 0.0
    for sequence in SEQUENCES:
        n = sequence_summaries[sequence]["frames"]
        if timing and sequence in timing["sequences"]:
            t = timing["sequences"][sequence]
            per_frame = float(t["mean_preprocess_s"] + t["mean_inference_s"])
            value = n * per_frame
            global_rows[sequence] = {"estimated_s": value, "per_frame_s": per_frame,
                                     "source": "AVL-005 eight-sample frozen Top-10 Reloc3r timing"}
            global_total += value
        if retrieval and sequence in retrieval["sequences"]:
            retrieval_total += float(retrieval["sequences"][sequence]["total_s"])
    recovery_calls = 0
    recovery_roma_s = 0.0
    for sequence, trace_rows in traces_by_sequence.items():
        for row in trace_rows:
            rec = row["global_temporal_memory_roma_recovery"]
            if rec["selected_action"] == "call_roma":
                recovery_calls += 1
                recovery_roma_s += float(rec.get("evidence", {}).get("roma_elapsed_s", 0.0))
    # The cache's per-call timing is not embedded in the trace evidence, so use the raw rows for the exact selected set.
    for sequence, trace_rows in traces_by_sequence.items():
        raw = args.roma_root / f"{sequence}_top100_merged.jsonl"
        cache = {}
        if raw.exists():
            for line in raw.read_text(encoding="utf-8").splitlines():
                row = json.loads(line); cache[int(row["query_index"])] = row
        for row in trace_rows:
            rec = row["global_temporal_memory_roma_recovery"]
            if rec["selected_action"] == "call_roma" and rec["query_index"] in cache:
                recovery_roma_s += float(cache[rec["query_index"]].get("elapsed_s", 0.0))
    # The previous loop starts at zero for this ledger; avoid double counting the empty evidence path.
    manager_frames = sum(sequence_summaries[s]["frames"] for s in SEQUENCES)
    roma_full = args.cost_root / "summary.json"
    old = json.loads(roma_full.read_text(encoding="utf-8")) if roma_full.exists() else None
    roma_per_call = None
    if old:
        roma_per_call = sum(old["sequences"][s]["roma"]["elapsed_s"]["sum_s"] for s in SEQUENCES) / manager_frames
    memory_proxy = None
    verification_proxy = None
    if old:
        memory_proxy = float(old["comparison"]["manager"].get("memory_s", 0.0))
        verification_proxy = float(old["comparison"]["manager"].get("verification_s", 0.0))
    known_total = global_total + temporal_total + retrieval_total + recovery_roma_s + (memory_proxy or 0.0) + (verification_proxy or 0.0)
    return {
        "protocol": "AVL-009 serial cost ledger; call-rate is not converted into latency",
        "temporal_reloc3r": {"sum_s": temporal_total, "by_sequence": temporal_rows,
                             "note": "measured inference batch wall time; preprocessing was not separately instrumented in the first edge run"},
        "global_reloc3r": {"estimated_sum_s": global_total, "by_sequence": global_rows,
                           "note": "sample-scaled estimate inherited from AVL-005, not a new full-frame timing run"},
        "retrieval": {"sum_s": retrieval_total, "source": str(retrieval_path) if retrieval else None},
        "roma_recovery": {"calls": recovery_calls, "cached_elapsed_s": recovery_roma_s,
                          "note": "replayed fixed-seed no-GT RoMa cache; no new online GPU timing"},
        "roma_always_reference": {"mean_per_frame_s": roma_per_call,
                                  "source": "AVL-005 unified_cost/summary.json"},
        "memory": {"estimated_s": memory_proxy,
                    "source": "AVL-005 manager CPU timing proxy; AVL-009 memory timing was not separately instrumented"},
        "reference_reranking": {"measured_s": None,
                                 "note": "AVL-009 recovery replay consumed an existing no-GT cache; reranking was not rerun in this baseline"},
        "verification": {"estimated_s": verification_proxy,
                          "note": "AVL-005 manager CPU timing proxy; AVL-009 verification timing was not separately instrumented"},
        "total_serial_latency": {"known_components_s": known_total,
                                  "known_components": ["global_reloc3r_estimate", "temporal_reloc3r_inference", "retrieval", "cached_roma_recovery", "memory_proxy", "verification_proxy"],
                                  "gpu_hours_estimate": (global_total + temporal_total + recovery_roma_s) / 3600.0},
        "warning": "This is a transparent mixed measured/estimated ledger; it does not establish an end-to-end speedup claim.",
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-root", type=Path, required=True)
    parser.add_argument("--trace-root", type=Path, required=True)
    parser.add_argument("--temporal-root", type=Path, required=True)
    parser.add_argument("--roma-root", type=Path, required=True)
    parser.add_argument("--cost-root", type=Path, required=True)
    parser.add_argument("--roma-timed-root", type=Path)
    parser.add_argument("--gt-dir", type=Path, required=True)
    parser.add_argument("--mapping-gt", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--max-gt-delta", type=float, default=0.1)
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "validation").mkdir(exist_ok=True)
    (args.output_dir / "test").mkdir(exist_ok=True)
    (args.output_dir / "all").mkdir(exist_ok=True)
    (args.output_dir / "failure_analysis").mkdir(exist_ok=True)
    (args.output_dir / "cost").mkdir(exist_ok=True)

    traces_by_sequence = {}
    all_results = {"validation": {}, "test": {}, "all": {}}
    seq_summaries = {}
    for sequence in SEQUENCES:
        _, _, query_times, _, query_root = read_manifest(args.data_root, sequence)
        query_gt, query_delta = tum_camera_poses(args.gt_dir / f"{sequence}_gt_poses.txt", query_times,
                                                  base_to_front_rgb_optical(query_root), args.max_gt_delta)
        trace_rows = load_trace(args.trace_root, sequence)
        traces_by_sequence[sequence] = trace_rows
        n = len(trace_rows)
        split = int(math.ceil(0.4 * n))
        seq_summaries[sequence] = {"frames": n, "validation_frames": split, "test_frames": n - split,
                                   "gt_match_delta_max_s": float(query_delta.max())}
        method_results = {"validation": {}, "test": {}, "all": {}}
        for method in METHODS[:-1]:
            predictions, method_rows = method_predictions(trace_rows, method)
            actions = [r.get("selected_action") for r in method_rows]
            sources = [r.get("prediction_source") for r in method_rows]
            method_results["validation"][method] = metrics_from_predictions(predictions, query_gt, query_times,
                                                                                0, split, actions, sources)
            method_results["test"][method] = metrics_from_predictions(predictions, query_gt, query_times,
                                                                        split, n, actions, sources)
            method_results["all"][method] = metrics_from_predictions(predictions, query_gt, query_times,
                                                                       0, n, actions, sources)
        roma = load_always_roma(args.cost_root / "eval_roma_seed0" / f"{sequence}.json",
                                (args.roma_timed_root / f"{sequence}.jsonl") if args.roma_timed_root else None)
        if all(finite_pose(p) for p in roma["predictions"]):
            roma_actions = roma["actions"]
            roma_sources = roma["sources"]
            method_results["validation"]["always_roma"] = metrics_from_predictions(roma["predictions"], query_gt, query_times,
                                                                                       0, split, roma_actions, roma_sources)
            method_results["test"]["always_roma"] = metrics_from_predictions(roma["predictions"], query_gt, query_times,
                                                                                 split, n, roma_actions, roma_sources)
            method_results["all"]["always_roma"] = metrics_from_predictions(roma["predictions"], query_gt, query_times,
                                                                                0, n, roma_actions, roma_sources)
        else:
            method_results["validation"]["always_roma"] = metrics_from_always_roma(roma, query_times, 0, split)
            method_results["test"]["always_roma"] = metrics_from_always_roma(roma, query_times, split, n)
            method_results["all"]["always_roma"] = metrics_from_always_roma(roma, query_times, 0, n)
        for split_name in method_results:
            result = {"experiment": "AVL-009", "sequence": sequence, "split": split_name,
                      "thresholds_frozen": True, "same_scene_temporal_holdout": True,
                      "query_gt_read_by_online_trace": False, "methods": method_results[split_name]}
            all_results[split_name][sequence] = result
            out_file = args.output_dir / split_name / f"{sequence}.json"
            out_file.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")

    for split_name in all_results:
        all_results[split_name]["aggregate"] = aggregate_metrics({s: all_results[split_name][s]["methods"] for s in SEQUENCES})
    summary = {"experiment": "AVL-009", "protocol": {
        "validation_fraction": 0.4, "test_fraction": 0.6, "thresholds_frozen_before_test": True,
        "same_scene_temporal_holdout": True, "query_gt_online": False, "future_frame_online": False,
        "no_agent": True,
    }, "sequences": seq_summaries, "validation": all_results["validation"], "test": all_results["test"],
               "all": all_results["all"]}
    (args.output_dir / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")

    failure_analysis = {}
    for condition, sequence in (("static", "static_0"), ("dynamic", "dynamics_0"),
                                ("long_term_change", "lt_changes_0"), ("dynamic_plus_long_term", "lt_changes_dynamics_0")):
        failure_analysis[condition] = {method: all_results["test"][sequence]["methods"].get(method) for method in METHODS}
    (args.output_dir / "failure_analysis" / "condition_test_metrics.json").write_text(
        json.dumps({"experiment": "AVL-009", "conditions": failure_analysis,
                    "interpretation": "condition labels are sequence-level operational labels, not causal semantic GT"}, indent=2) + "\n",
        encoding="utf-8")
    ledger = cost_ledger(args, traces_by_sequence, seq_summaries)
    (args.output_dir / "cost" / "summary.json").write_text(json.dumps(ledger, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"validation": all_results["validation"]["aggregate"], "test": all_results["test"]["aggregate"], "cost": ledger}, indent=2))


if __name__ == "__main__":
    main()
